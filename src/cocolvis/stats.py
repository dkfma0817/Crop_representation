"""Step 0: COCO 2017 / LVIS v1 data + protocol checks (CPU only).

  python -m src.cocolvis.stats --out output/2026-11-07/cocolvis_headroom/data
Writes data_check.json / data_check.md, class_counts_{coco,lvis}.csv, image_sizes.json (ACTUAL file sizes) and
instances_{ds}_{split}.parquet (the exact ROI tables every later step uses).
"""
import argparse
import hashlib
import json
import os
from multiprocessing import Pool

import numpy as np
import pandas as pd
from PIL import Image

from src.cocolvis.common import ANN, load
from src.vaw.dhash import dhash


def _meta(p):
    with Image.open(p) as im:
        W, H = im.size
    h = hashlib.md5(open(p, "rb").read()).hexdigest()
    return W, H, h, dhash(p)


def pct(a, b):
    return f"{a:,} ({100 * a / b:.2f}%)" if b else f"{a:,}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    R, md = {}, ["# COCO 2017 / LVIS v1 data check (auto-generated by src.cocolvis.stats)", ""]
    T, raw = {}, {}
    for ds in ("coco", "lvis"):
        for sp in ("train", "val"):
            raw[(ds, sp)] = json.load(open(ANN[(ds, sp)]))
            T[(ds, sp)], imgs, cats = load(ds, sp, raw[(ds, sp)])
    # ---- image files: existence, ACTUAL size, md5, dHash (union of all images used)
    paths = sorted(set().union(*[set(D.path) for D in T.values()]))
    with Pool(64) as p:
        M = p.map(_meta, paths, chunksize=64)
    meta = dict(zip(paths, M))
    sizes = {pth: (m[0], m[1]) for pth, m in meta.items()}
    json.dump({os.path.relpath(k, "/home/irteam/datasets/coco"): v for k, v in sizes.items()}, open(os.path.join(a.out, "image_sizes.json"), "w"))
    for key, D in T.items():
        ds, sp = key
        J = raw[key]
        wh = np.array([sizes[pth] for pth in D.path])
        bad_wh = int(((wh[:, 0] != D.W.values) | (wh[:, 1] != D.H.values)).sum())
        D["W"], D["H"] = wh[:, 0], wh[:, 1]                                     # actual file size
        x1, y1 = D.x + D.w, D.y + D.h
        out_of_img = int(((D.x < 0) | (D.y < 0) | (x1 > D.W) | (y1 > D.H)).sum())
        cx0, cy0 = D.x.clip(lower=0), D.y.clip(lower=0)
        cw, ch = np.minimum(x1, D.W) - cx0, np.minimum(y1, D.H) - cy0
        empty = (cw <= 0) | (ch <= 0)
        D.drop(index=D.index[empty], inplace=True)
        D.reset_index(drop=True, inplace=True)
        n_crowd = sum(1 for x in J["annotations"] if x.get("iscrowd", 0)) if ds == "coco" else 0
        npi = D.groupby("image_id").size()
        r = dict(images_in_json=len(J["images"]), images_with_roi=int(D.image_id.nunique()),
                 annotations_in_json=len(J["annotations"]), crowd_excluded=n_crowd, empty_after_clip_dropped=int(empty.sum()),
                 rois=len(D), sizes={k: int((D["size"] == i).sum()) for i, k in enumerate("SML")},
                 rois_per_image=dict(mean=float(npi.mean()), median=float(npi.median()), p99=float(npi.quantile(0.99)), max=int(npi.max()),
                                     images_gt32=int((npi > 32).sum())),
                 boxes_outside_image=out_of_img, json_size_mismatch_rois=bad_wh,
                 box_lt_1px=int(((D.w < 1) | (D.h < 1)).sum()),
                 classes_present=int(D.label.nunique()))
        if ds == "lvis":
            ims = J["images"]
            r["image_source"] = pd.Series([im["coco_url"].split("/")[-2] for im in ims]).value_counts().to_dict()
            r["neg_category_ids_per_image_mean"] = float(np.mean([len(im["neg_category_ids"]) for im in ims]))
            r["not_exhaustive_per_image_mean"] = float(np.mean([len(im["not_exhaustive_category_ids"]) for im in ims]))
            r["images_with_not_exhaustive"] = int(sum(1 for im in ims if im["not_exhaustive_category_ids"]))
        R[f"{ds}_{sp}"] = r
        D.to_parquet(os.path.join(a.out, f"instances_{ds}_{sp}.parquet"))
    # ---- overlaps (by file = COCO image identity; md5 exact; dHash 0 near-exact)
    ov = {}
    files = {k: set(D.path) for k, D in T.items()}
    md5 = {k: {meta[pth][2] for pth in v} for k, v in files.items()}
    dh = {k: {meta[pth][3] for pth in v} for k, v in files.items()}
    for x, y in [(("coco", "train"), ("coco", "val")), (("lvis", "train"), ("lvis", "val")),
                 (("coco", "train"), ("lvis", "val")), (("lvis", "train"), ("coco", "val"))]:
        k = f"{x[0]}_{x[1]} vs {y[0]}_{y[1]}"
        ov[k] = dict(same_file=len(files[x] & files[y]), md5_identical=len(md5[x] & md5[y]), dhash_identical=len(dh[x] & dh[y]))
    R["overlap"] = ov
    lv = {k: pd.Series([raw[("lvis", k)]["images"][i]["coco_url"].split("/")[-2] for i in range(len(raw[("lvis", k)]["images"]))]).value_counts().to_dict()
          for k in ("train", "val")}
    R["lvis_from_coco"] = lv
    # ---- class counts
    for ds in ("coco", "lvis"):
        cats = sorted(raw[(ds, "train")]["categories"], key=lambda c: c["id"])
        tr, va = T[(ds, "train")], T[(ds, "val")]
        C = pd.DataFrame(dict(label=range(len(cats)), cat_id=[c["id"] for c in cats], name=[c["name"] for c in cats]))
        C["train_rois"] = tr.groupby("label").size().reindex(C.label, fill_value=0).values
        C["train_images"] = tr.groupby("label").image_id.nunique().reindex(C.label, fill_value=0).values
        C["val_rois"] = va.groupby("label").size().reindex(C.label, fill_value=0).values
        if ds == "lvis":
            C["frequency"] = [c["frequency"] for c in cats]
            C["json_image_count"] = [c["image_count"] for c in cats]
        C.to_csv(os.path.join(a.out, f"class_counts_{ds}.csv"), index=False)
        cc = dict(train_rois_min=int(C.train_rois.min()), train_rois_median=float(C.train_rois.median()), train_rois_max=int(C.train_rois.max()),
                  classes_zero_train=int((C.train_rois == 0).sum()), classes_in_val=int((C.val_rois > 0).sum()))
        if ds == "lvis":
            for f in "rcf":
                s = C[C.frequency == f]
                cc[f] = dict(classes=len(s), in_val=int((s.val_rois > 0).sum()), train_rois_median=float(s.train_rois.median()),
                             train_rois_min=int(s.train_rois.min()), train_rois_max=int(s.train_rois.max()),
                             train_rois_sum=int(s.train_rois.sum()), val_rois=int(s.val_rois.sum()), zero_train=int((s.train_rois == 0).sum()))
            cc["train_roi_share_rcf"] = {f: float(C[C.frequency == f].train_rois.sum() / C.train_rois.sum()) for f in "rcf"}
        R[f"classes_{ds}"] = cc
    json.dump(R, open(os.path.join(a.out, "data_check.json"), "w"), indent=1, default=int)
    print(json.dumps(R, indent=1, default=int))


if __name__ == "__main__":
    main()
