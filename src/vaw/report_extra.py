"""VAW report, post-hoc analyses on the SAME saved test probabilities (no retraining, no selection change). CPU only.

(1) G1 exposure: Δ(G1 − Frozen) on the G1-exposed test images vs on the leak-free test images, and the difference of the
    two (paired image bootstrap: exposed and leak-free images are resampled independently within their own set).
(2) Parent attribute type (official attribute_parent_types): Δ and 95% CI on the full test for every contrast.

  python -m src.vaw.report_extra --run output/2026-11-07/vaw_g1
"""
import argparse
import json
import os

import numpy as np

from src.vaw.common import attr_index, label_matrix, load_split
from src.vaw.probe import official_evaluator
from src.vaw.report import CONDS, CONTRASTS, FastAP, official

B, SEED = 1000, 0


def boot_w(n, rng):
    return rng.multinomial(n, np.full(n, 1.0 / n), size=B).astype(np.float64)


def subset(prob, Y, img, m, i2a, conds):
    Ys = Y[m]
    excl = [i2a[j] for j in range(620) if not ((Ys[:, j] == 1).any() and (Ys[:, j] == 0).any())]
    ok = np.array([i2a[j] not in set(excl) for j in range(620)])
    uimg, rimg = np.unique(img[m], return_inverse=True)
    pts, fast = {}, {}
    for c in conds:
        pts[c], pcap = official(prob[c][m], Ys, i2a, excl)
        fast[c] = FastAP(prob[c][m], Ys, rimg, ok)
        assert np.nanmax(np.abs(fast[c].ap(np.ones(len(uimg))) - pcap[fast[c].cls])) < 1e-9
    return dict(n_images=len(uimg), n_instances=int(m.sum()), n_attr_excluded=len(excl)), pts, fast, len(uimg)


def ci(v):
    return float(np.nanpercentile(v, 2.5)), float(np.nanpercentile(v, 97.5))


def main():
    ap_ = argparse.ArgumentParser()
    ap_.add_argument("--run", required=True)
    a = ap_.parse_args()
    a2i, i2a = attr_index()
    X = load_split("test")
    Y = label_matrix(X, a2i)
    img = np.array([int(x["image_id"]) for x in X])
    sub = json.load(open(os.path.join(a.run, "leak", "subsets.json")))
    exposed = np.isin(img, sub["g1_exposed_test_images"])
    conds = list(CONDS)
    prob = {c: np.load(os.path.join(a.run, c, "test_prob.npy")) for c in conds}
    rng = np.random.default_rng(SEED)
    out = dict(note="post-hoc analysis on saved test predictions; CI = image bootstrap, single probe seed 0", exposure={}, types={})

    # (1) exposure
    g1c = ["frozen_full", "g1pool_full", "g1cross_full"]
    info, P, F, W = {}, {}, {}, {}
    for s, m in (("exposed", exposed), ("leakfree", ~exposed)):
        info[s], P[s], F[s], n = subset(prob, Y, img, m, i2a, g1c)
        W[s] = boot_w(n, rng)
    apx = {s: {c: [F[s][c].ap(W[s][b]) for b in range(B)] for c in g1c} for s in P}
    for x in ("g1pool_full", "g1cross_full"):
        d = {}
        for s in P:
            v = []
            for b in range(B):
                ax, ay = apx[s][x][b], apx[s]["frozen_full"][b]
                k = ~(np.isnan(ax) | np.isnan(ay))
                v.append(100 * (ax[k].mean() - ay[k].mean()))
            d[s] = np.array(v)
        r = {}
        for s in P:
            lo, hi = ci(d[s])
            r[s] = dict(delta=P[s][x]["mAP"] - P[s]["frozen_full"]["mAP"], lo=lo, hi=hi)
        lo, hi = ci(d["exposed"] - d["leakfree"])
        r["exposed_minus_leakfree"] = dict(delta=r["exposed"]["delta"] - r["leakfree"]["delta"], lo=lo, hi=hi)
        out["exposure"][f"{x} - frozen_full"] = r
    out["exposure_subsets"] = info
    out["exposure_points"] = {s: {c: P[s][c]["mAP"] for c in g1c} for s in P}

    # (2) parent types on full test
    ev = official_evaluator()
    info_all, Pa, Fa, n = subset(prob, Y, img, np.ones(len(X), bool), i2a, conds)
    Wa = boot_w(n, rng)
    types = list(ev.attribute_parent_type)
    tmask = {t: np.array([ev.get_attr_type(i2a[j])[0] == t for j in Fa[conds[0]].cls]) for t in types}
    ap_b = {c: [Fa[c].ap(Wa[b]) for b in range(B)] for c in conds}       # per-class AP per resample, computed once
    for x, y in CONTRASTS:
        r = {}
        for t in types:
            v = []
            for b in range(B):
                ax, ay = ap_b[x][b], ap_b[y][b]
                k = ~(np.isnan(ax) | np.isnan(ay)) & tmask[t]
                v.append(100 * (ax[k].mean() - ay[k].mean()) if k.any() else np.nan)
            lo, hi = ci(np.array(v))
            r[t] = dict(n_attr=int(tmask[t].sum()), delta=Pa[x][f"mAP_{t}"] - Pa[y][f"mAP_{t}"], lo=lo, hi=hi)
        out["types"][f"{x} - {y}"] = r
    json.dump(out, open(os.path.join(a.run, "results_extra.json"), "w"), indent=1)

    f = lambda c: f"{c['delta']:+.2f} [{c['lo']:+.2f}, {c['hi']:+.2f}]" + ("*" if c["lo"] > 0 or c["hi"] < 0 else "")  # noqa: E731
    L = ["# VAW post-hoc analyses (auto-generated by src.vaw.report_extra)", "", out["note"], "",
         "## (1) G1-exposed vs leak-free test images", "",
         "| subset | images | instances | attrs excluded | Frozen | G1-pool | G1-cross |", "|---|---:|---:|---:|---:|---:|---:|"]
    for s in P:
        L.append(f"| {s} | {info[s]['n_images']:,} | {info[s]['n_instances']:,} | {info[s]['n_attr_excluded']} | "
                 + " | ".join(f"{P[s][c]['mAP']:.2f}" for c in g1c) + " |")
    L += ["", "| contrast | Δ exposed | Δ leak-free | exposed − leak-free |", "|---|---|---|---|"]
    for k, r in out["exposure"].items():
        L.append(f"| {k} | {f(r['exposed'])} | {f(r['leakfree'])} | {f(r['exposed_minus_leakfree'])} |")
    L += ["", "## (2) mAP by parent attribute type, full test (Δ, 95% CI)", "",
          "| contrast | " + " | ".join(f"{t} ({out['types'][CONTRASTS[0][0] + ' - ' + CONTRASTS[0][1]][t]['n_attr']})" for t in types) + " |",
          "|---|" + "---|" * len(types)]
    for k, r in out["types"].items():
        L.append(f"| {k} | " + " | ".join(f(r[t]) for t in types) + " |")
    open(os.path.join(a.run, "results_extra.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
